"""Write the four src/*.liquid layouts from one body and four knob blocks.

The layouts are one template that differs only in its knobs, and hand
editing four copies is how they drift. `scripts/check.sh` regenerates and
fails if the working tree disagrees, so the body below is the only place
the render is written.
"""
import os, pathlib, sys

# The merge-variable node the markup reads. The tree always holds the
# placeholder; `NODE=google_calendar_<id> python3 scripts/gen_layouts.py`
# writes the real one for a `trmnlp push`, and `--check` compares against
# whatever NODE says, so a real node never passes the check unnoticed.
NODE = os.environ.get('NODE', 'google_calendar_12345')

BODY = pathlib.Path(__file__).with_name('layout_body.liquid').read_text()
AGENDA = pathlib.Path(__file__).with_name('agenda_body.liquid').read_text()
# The body is the derived section, then the grid render from its <style>.
# The agenda view shares the derived section and replaces the render.
_split = BODY.index('\n<style>')
DERIVED, GRID = BODY[:_split], BODY[_split:]
BODY = (DERIVED
        + '\n{%- if MODE == "agenda" -%}\n' + AGENDA
        + '\n{%- else -%}' + GRID + '\n{%- endif -%}\n')

SHARED = """{%- assign src = @NODE@ -%}

{%- comment -%} ---- colours: overridden by the plugin's custom fields ---- {%- endcomment -%}
{%- assign CAL_MAP_DEFAULT = "you@gmail.com=black,work@example.com=red,shared@group.calendar.google.com=yellow" -%}
{%- assign DEFAULT_COLOR_FALLBACK = "black" -%}
{%- comment -%} fills that take BLACK text. On the B/W/R/Y panel orange is a red-and-yellow
     tile and pink a red-and-white one. A -45..-75 step is the hue's dots on a white ground,
     and yellow-10..-40 is yellow under a sparse black dot; all of those stay light. A grey's
     number is its lightness (gray-75 is nearly white, gray-10 nearly black), measured in the
     framework's 1-bit tiles, so gray-40 and up take black text. {%- endcomment -%}
{%- assign LIGHT_FILLS = "white,yellow,orange,pink,yellow-10,yellow-15,yellow-20,yellow-25,yellow-30,yellow-35,yellow-40,yellow-45,yellow-50,yellow-55,yellow-60,yellow-65,yellow-70,yellow-75,orange-45,orange-50,orange-55,orange-60,orange-65,orange-70,orange-75,pink-45,pink-50,pink-55,pink-60,pink-65,pink-70,pink-75,red-45,red-50,red-55,red-60,red-65,red-70,red-75,gray-40,gray-45,gray-50,gray-55,gray-60,gray-65,gray-70,gray-75" | split: "," -%}

{%- comment -%} ---- layout ---- {%- endcomment -%}
{%- assign SHOW_ALLDAY = true -%}
{%- assign HIGHLIGHT_TODAY = true -%}
{%- assign DAY_FMT = "%a %-m/%-d" -%}
{%- assign HEAD_SIZE = "small" -%}   {%- comment -%} label--small is the framework's 12px pixel-hinted
                                          face (TRMNL12). label--xsmall is an ALIAS of the 16px one, so
                                          it is not smaller; nothing below 12px renders without fuzz. {%- endcomment -%}
{%- assign AXIS_MODE_FALLBACK = "fit" -%}
{%- assign EMPTY_START_H = 8 -%}
{%- assign EMPTY_END_H = 18 -%}
{%- assign LINE_H = 12 -%}
{%- assign TIGHT_LINE_H = 10 -%}   {%- comment -%} the smaller line a block drops to when its text does not fit its minutes {%- endcomment -%}
{%- assign CHAR_W100 = 712 -%}   {%- comment -%} hundredths of a px per character of the BOLD 12px face: 6.72
                                      measured in the live preview, plus the margin the regular face had {%- endcomment -%}
{%- assign MAX_DEPTH = 4 -%}     {%- comment -%} nesting steps a block is indented for; deeper ones share the last step {%- endcomment -%}
{%- assign MIN_AXIS_DUR = 5 -%}   {%- comment -%} minutes: shorter than this and the event does not move the axis {%- endcomment -%}
"""

LAYOUTS = {
    # view              days panelW axis panelH head (unused) hmax every legend indent
    'full':            (3, 780, 39, 460, 18, 44, 24, 1, 'true', 24),
    'half_horizontal': (3, 780, 39, 220, 18, 36, 16, 3, 'true', 24),
    'half_vertical':   (2, 380, 40, 460, 18, 44, 22, 2, 'false', 16),
    'quadrant':        (2, 380, 34, 220, 18, 36, 15, 3, 'false', 16),
}

HEAD = """{%- comment -%}
=====================================================================
 Google Calendar fork - per-calendar colour coding (TRMNL Plugin Merge)
 Layout: @VIEW@
 View:   Week time grid. Hours down the left axis, one column per day
         (the layout's span, or today only when "Days shown" is 1).
         Every event is a solid filled block carrying its start
         time, end time and title in full. Blocks sit at their clock
         position; a block that starts inside another is indented and
         painted over it, as the native render does, but never over
         the other block's text.
=====================================================================
 GENERATED by scripts/gen_layouts.py from scripts/layout_body.liquid.
 Edit those, run the script, never these files.
=====================================================================
 SETUP
   1. Connect Google Calendar natively, pick your calendars, hide the
      instance on the playlist so it keeps syncing.
   2. New Private Plugin -> Strategy: Plugin Merge.
   3. Open "Merge Variables", find your node (google_calendar_<id>) and
      replace the placeholder on the `assign src` line below.
   4. Set the colours on the plugin's settings page, not here: the
      "Calendar colors" field takes one `calendar-id=colour` per line and
      "Default color" covers anything unlisted. The defaults below apply
      only while those fields are empty.

 COLOURS. On the TRMNL OG (B/W/R/Y) panel only black, white, red and
 yellow are solid inks. orange (red+yellow tile), pink (red+white tile)
 and the -45..-75 tints (the hue's dots on white) are usable blends;
 grey steps are for 1-bit and TRMNL X panels only.
=====================================================================
{%- endcomment -%}

"""

KNOBS = """{%- comment -%} ---- this layout ---- {%- endcomment -%}
{%- assign VIEW = "@VIEW@" -%}
{%- assign NUM_DAYS = @DAYS@ -%}          {%- comment -%} day columns, starting today {%- endcomment -%}
{%- assign PANEL_W = @PANEL@ -%}         {%- comment -%} USABLE width: the panel less the framework .screen's 10px
                                            box inset on each side. The columns divide it into whole px {%- endcomment -%}
{%- assign AXIS_W = @AXIS@ -%}           {%- comment -%} chosen so (PANEL_W - AXIS_W) / NUM_DAYS is exact {%- endcomment -%}
{%- assign PANEL_H = @PANELH@ -%}        {%- comment -%} USABLE height, same inset. The grid gets what the day
                                            headers, the all-day band and the legend leave of it {%- endcomment -%}
{%- assign HEAD_H = @HEADH@ -%}          {%- comment -%} day-header row, measured in the rendered preview {%- endcomment -%}
{%- assign HOUR_H_MAX = @HMAX@ -%}         {%- comment -%} px per hour ceiling {%- endcomment -%}
{%- assign HOUR_EVERY = @EVERY@ -%}         {%- comment -%} label every Nth hour {%- endcomment -%}
{%- assign INDENT_W = @INDENT@ -%}         {%- comment -%} px a nested block steps right per open block above it {%- endcomment -%}
{%- assign SHOW_LEGEND = @LEGEND@ -%}

"""

def render(view):
    (days, panel, axis, panel_h, head_h, title_h, hmax, every,
     legend, indent) = LAYOUTS[view]
    subs = {'@NODE@': NODE, '@VIEW@': view, '@DAYS@': days, '@PANEL@': panel, '@AXIS@': axis,
            '@PANELH@': panel_h, '@HEADH@': head_h,
            '@HMAX@': hmax, '@EVERY@': every,
            '@LEGEND@': legend,
            '@INDENT@': indent}
    out = HEAD + SHARED + '\n' + KNOBS + BODY
    for k, v in subs.items():
        out = out.replace(k, str(v))
    return out

if __name__ == '__main__':
    check = '--check' in sys.argv
    root = pathlib.Path(__file__).resolve().parent.parent
    bad = []
    for view in LAYOUTS:
        p = root / 'src' / f'{view}.liquid'
        out = render(view)
        if check:
            if not p.exists() or p.read_text() != out:
                bad.append(str(p))
        else:
            p.write_text(out)
    if check and bad:
        print('FAIL: regenerate the layouts - ' + ', '.join(bad))
        sys.exit(1)
    print('layouts checked' if check else 'layouts written')
